def main():
    engine = create_engine(DATABASE_URL)

    inserted = 0
    updated = 0

    with engine.begin() as conn:
        for name, desc_th in RISK_FACTORS:
            row = conn.execute(
                text("""
                    INSERT INTO risk_factor (factor_name, description_th)
                    VALUES (:name, :desc_th)
                    ON CONFLICT (factor_name) DO UPDATE
                        SET description_th = EXCLUDED.description_th
                    RETURNING factor_name, (xmax = 0) AS inserted
                """),
                {"name": name, "desc_th": desc_th},
            ).fetchone()
            action = "insert" if row[1] else "update"
            print(f"  [{action}] {row[0]}")
            if row[1]:
                inserted += 1
            else:
                updated += 1

    print(f"\nDone. Inserted: {inserted}, Updated: {updated}")


if __name__ == "__main__":
    main()
